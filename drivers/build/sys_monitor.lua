local p = ui.panel("System")
p:label("v", "FW: " .. tostring(sys.version()))
p:label("u", "Uptime: --")
p:label("tc", "CPU: --")
p:label("h", "Heap: --")
p:progress("hb", "Heap (of 300KB)", 0)
timer.every(1000, function()
  local u, h = sys.uptime(), sys.heap()
  p:set("u", string.format("Uptime: %dd %02d:%02d:%02d", u // 86400, u // 3600 % 24, u // 60 % 60, u % 60))
  p:set("tc", string.format("CPU: %.1f C", sys.temp()))
  p:set("h", string.format("Heap: %d KB", h // 1024))
  p:set("hb", math.min(100, h / 3000))
end)
function on_stop() end
